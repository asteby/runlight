// Builds the icon sprite (internal/dashboard/web/icons.svg) from lucide-static (ISC license).
// Usage:  npm i --prefix tools/icons   (once)   then   node tools/icons/build.mjs
// Reads icons.txt and, if present, extra-icons.txt (one name per line, '#' starts a comment).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(here, 'node_modules', 'lucide-static', 'icons');
const out = join(here, '..', '..', 'internal', 'dashboard', 'web', 'icons.svg');

const names = new Set();
for (const f of ['icons.txt', 'extra-icons.txt']) {
  const p = join(here, f);
  if (!existsSync(p)) continue;
  for (const line of readFileSync(p, 'utf8').split(/\r?\n/)) {
    const n = line.replace(/#.*/, '').trim();
    if (n) names.add(n);
  }
}

const missing = [];
const symbols = [];
for (const name of [...names].sort()) {
  if (!/^[a-z0-9-]+$/.test(name)) throw new Error('nombre de icono no válido: ' + name);
  const file = join(iconsDir, name + '.svg');
  if (!existsSync(file)) { missing.push(name); continue; }
  const src = readFileSync(file, 'utf8');
  const m = src.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error('SVG inesperado: ' + name);
  const body = m[1].replace(/\s*\n\s*/g, '').trim();
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`);
}
if (missing.length) {
  console.error('Faltan en lucide-static: ' + missing.join(', '));
  process.exit(1);
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by tools/icons/build.mjs from lucide-static (ISC License, https://lucide.dev). Do not edit. -->\n${symbols.join('\n')}\n</svg>\n`;
writeFileSync(out, svg);
console.log(`icons.svg: ${symbols.length} iconos, ${svg.length} bytes`);
